DATA = {"demo-watchlist": WATCHLIST, "demo-registry": REGISTRY, "demo-webfeed": WEBFEED}


def write_demo_file(source_id: str, path: Path, with_probes: bool = False) -> Path:
    rows = list(DATA[source_id])
    if with_probes and source_id == "demo-watchlist":
        rows += PROBES
    now = dt.datetime.now(dt.timezone.utc).replace(microsecond=0)
    exported = now - dt.timedelta(days=10) if source_id == "demo-webfeed" else now - dt.timedelta(hours=3)
    header = {"format": FORMAT, "schema_version": SCHEMA_VERSION, "exported_at": exported.isoformat(),
              "version": f"demo-{now:%Y%m%d}", "row_count": len(rows)}
    with open(path, "w", encoding="utf-8") as f:
        f.write(json.dumps(header) + "\n")
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    return path
