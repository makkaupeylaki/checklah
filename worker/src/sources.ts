// Source registry: what each connector is, its licence/attribution and staleness policy.
// `adapter: null` means no adapter exists and the source can never be imported or searched.

export type Mode = "demo" | "live";
export type Kind = "person" | "company" | "website" | "record" | "other";

export interface SourceDef {
  id: string;
  title: string;
  mode: Mode;
  kinds: Kind[];
  scope: string;
  licence: { name: string; url: string | null };
  /** Attribution text; `{accessed}` is replaced with the local import date. */
  attribution: string;
  homepage: string | null;
  refresh: string;
  adapter: "demo" | "acra" | "opensanctions" | null;
  blockedReason: string | null;
  /** Display defaults for per-source constants not stored on every row. */
  recordDefaults?: { datasetTitles?: Record<string, string>; link?: { label: string; url: string }; note?: string; identifierLabels?: Record<string, string> };
  /** Staleness: hours since local import / upstream export / last upstream check. */
  stale: { importHours?: number; upstreamHours?: number; checkHours?: number };
  notes: string[];
}

